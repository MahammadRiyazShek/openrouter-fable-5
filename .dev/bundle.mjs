/* ============================================================
   bundle.mjs — fold the whole app into one index.html
   ============================================================
   Run: node .dev/bundle.mjs [output-path]
   Default output: single-file/index.html

   Why this exists: a multi-file upload can arrive half-finished,
   and a single missing module takes the entire ES module graph
   down with it — the page renders and nothing works. One file
   cannot be partially uploaded. It also runs from file://,
   because a classic script has none of the module loader's
   origin restrictions.
   ============================================================ */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const OUT = resolve(ROOT, process.argv[2] || 'single-file/index.html');

/* Dependency order. config has no imports; app imports everything. */
const ORDER = ['config.js', 'store.js', 'api.js', 'ingest.js', 'render.js', 'app.js'];

const read = (p) => readFileSync(resolve(ROOT, p), 'utf8');

/* ---------- 1. module -> plain script body ---------- */

/* Matches a whole import statement, single- or multi-line. Lazy up to the
   first `from '...'` so a multi-line brace list can't swallow the next one. */
const IMPORT_RX = /^import\b[\s\S]*?from\s*['"][^'"]*['"]\s*;?[ \t]*\r?\n/gm;
const EXPORT_RX = /^export\s+(?=(?:const|let|var|function|async|class)\b)/gm;

const chunks = [];
for (const file of ORDER) {
  let src = read(`js/${file}`);
  const imports = (src.match(IMPORT_RX) || []).length;
  src = src.replace(IMPORT_RX, '').replace(EXPORT_RX, '');

  const leftover = src.match(/^\s*(import|export)\b.*/m);
  if (leftover) throw new Error(`${file}: module syntax survived stripping -> ${leftover[0].trim()}`);

  chunks.push(
    `/* ==== ${file} ${'='.repeat(Math.max(0, 58 - file.length))} */\n` +
    `${src.trim()}\n`
  );
  console.log(`  ${file.padEnd(12)} ${imports} import(s) removed`);
}

let js = `/* Blueprint — single-file build. Generated by .dev/bundle.mjs; edit js/*.js instead. */\n` +
  `(function () {\n'use strict';\n\n${chunks.join('\n')}\n})();\n`;

/* ---------- 2. make it safe to sit inside <script> ---------- */

/* An HTML parser inside a <script> element closes it at the first literal
   `</script`, string literal or not. render.js emits that sequence when it
   stitches a preview, so escape the slash: `<\/script` is the same string to
   JS and invisible to the parser. Only the closing form matters — a bare
   `<script` does not change the tokenizer state without a preceding `<!--`. */
const closers = (js.match(/<\/script/gi) || []).length;
js = js.replace(/<\/script/gi, '<\\/script');
console.log(`  escaped ${closers} literal </script sequence(s)`);

if (/<!--/.test(js)) throw new Error('bundle contains <!-- which would switch the HTML tokenizer into escaped state');

/* ---------- 3. stylesheet + favicon ---------- */

const css = read('styles.css');
if (/<\/style/i.test(css)) throw new Error('styles.css contains </style');

const svg = read('favicon.svg');
const favicon = 'data:image/svg+xml,' + encodeURIComponent(svg.replace(/\n\s*/g, ''));

/* ---------- 4. rewrite the shell ---------- */

let html = read('index.html');

const swap = (needle, replacement, label) => {
  if (!html.includes(needle)) throw new Error(`index.html: could not find ${label}`);
  html = html.replace(needle, () => replacement);
};

swap(
  '<link rel="stylesheet" href="styles.css" />',
  `<style>\n${css.trim()}\n</style>`,
  'the stylesheet link',
);

swap(
  '<link rel="icon" href="favicon.svg" type="image/svg+xml" />',
  `<link rel="icon" href="${favicon}" type="image/svg+xml" />`,
  'the favicon link',
);

/* Tells the boot watchdog to give single-file advice instead of listing files
   that, in this build, cannot possibly be missing. */
swap(
  'window.__bpBoot = false;',
  'window.__bpBoot = false;\nwindow.__bpSingle = true;',
  'the boot flag',
);

/* From file:// an href of "./" lands on a directory listing. */
swap('<a class="mark" href="./"', '<a class="mark" href="#"', 'the wordmark link');

swap(
  '<script type="module" src="js/app.js"></script>',
  `<script>\n${js}</script>`,
  'the module script tag',
);

html = html.replace(
  '<!DOCTYPE html>',
  `<!DOCTYPE html>\n<!-- Blueprint, single-file build. Everything is in this one file:\n` +
  `     upload it on its own and there is nothing left to go missing.\n` +
  `     Source lives in js/*.js + styles.css; rebuild with: node .dev/bundle.mjs -->`,
);

/* ---------- 5. write ---------- */

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, html, 'utf8');

const kb = (Buffer.byteLength(html) / 1024).toFixed(1);
console.log(`\n  wrote ${OUT.replace(ROOT + '/', '')} — ${kb} KB, 1 file, 0 dependencies`);
